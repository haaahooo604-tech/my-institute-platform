-- Auxiliary tables only. This script does not delete or alter your seven existing subject tables.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default '',
 student_code text,
 age int,
 phone text,
 avatar_url text,
 role text not null default 'student' check (role in ('student','admin','supervisor')),
 created_at timestamptz not null default now()
);
create table if not exists public.announcements (
 id bigint generated by default as identity primary key,
 title text not null,
 body text not null,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create table if not exists public.materials (
 id bigint generated by default as identity primary key,
 subject text not null,
 title text not null,
 url text not null,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create table if not exists public.support_tickets (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 subject text not null,
 body text not null,
 status text not null default 'جديد',
 admin_reply text,
 created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
create or replace function public.is_platform_admin() returns boolean
language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role in ('admin','supervisor')) $$;
alter table public.announcements enable row level security;
alter table public.materials enable row level security;
alter table public.support_tickets enable row level security;

drop policy if exists "profile read own or admin" on public.profiles;
create policy "profile read own or admin" on public.profiles for select to authenticated using (auth.uid() = id or public.is_platform_admin());
drop policy if exists "profile insert own" on public.profiles;
create policy "profile insert own" on public.profiles for insert to authenticated with check (auth.uid() = id and role='student');
drop policy if exists "profile update own" on public.profiles;
create policy "profile update own" on public.profiles for update to authenticated using (auth.uid()=id) with check (auth.uid()=id and role='student');
drop policy if exists "announcements read" on public.announcements;
create policy "announcements read" on public.announcements for select to authenticated using (true);
drop policy if exists "announcements admin insert" on public.announcements;
create policy "announcements admin insert" on public.announcements for insert to authenticated with check (public.is_platform_admin());
drop policy if exists "materials read" on public.materials;
create policy "materials read" on public.materials for select to authenticated using (true);
drop policy if exists "materials admin insert" on public.materials;
create policy "materials admin insert" on public.materials for insert to authenticated with check (public.is_platform_admin());
drop policy if exists "ticket own or admin read" on public.support_tickets;
create policy "ticket own or admin read" on public.support_tickets for select to authenticated using (auth.uid()=user_id or public.is_platform_admin());
drop policy if exists "ticket own insert" on public.support_tickets;
create policy "ticket own insert" on public.support_tickets for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "ticket admin update" on public.support_tickets;
create policy "ticket admin update" on public.support_tickets for update to authenticated using (public.is_platform_admin()) with check (public.is_platform_admin());
